class CompilerTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.home = Path(self.temporary.name)
        self.directory = instructions_dir_for(self.home)
        self.directory.mkdir(parents=True)
        self.index = instructions_index_for(self.home)
        self.output = agents_file_for(self.home)
        self.index.write_text("# Ordered chapters\n\none.md\nparts/two.md\n")
        (self.directory / "parts").mkdir()
        (self.directory / "one.md").write_text("# First\nKeep **all** content.\n")
        (self.directory / "parts/two.md").write_text("# Second\nNo trailing newline")

    def test_order_complete_contents_and_noop_preserves_inode(self):
        self.assertTrue(build(self.home))
        content = self.output.read_text()
        self.assertIn("Generated by swe instructions build", content)
        self.assertIn("<!-- Source: AGENTS_MD/one.md -->", content)
        self.assertIn("# First\nKeep **all** content.\n", content)
        self.assertIn("# Second\nNo trailing newline\n", content)
        self.assertLess(content.index("# First"), content.index("# Second"))
        self.assertTrue(content.endswith("\n"))
        self.assertFalse(content.endswith("\n\n"))
        before = self.output.stat()
        self.assertFalse(build(self.home))
        self.assertEqual(before, self.output.stat())

    def test_check_detects_missing_and_tampered_output_without_replacing(self):
        self.assertTrue(build(self.home, check=True))
        self.assertFalse(self.output.exists())
        build(self.home)
        self.assertFalse(build(self.home, check=True))
        self.output.write_text("tampered")
        before = self.output.stat()
        self.assertTrue(build(self.home, check=True))
        self.assertEqual(self.output.read_text(), "tampered")
        self.assertEqual(before, self.output.stat())

    def test_atomic_build_preserves_mode_and_existing_harness_alias(self):
        self.output.write_text("old instructions")
        self.output.chmod(0o640)
        alias = self.home / "CLAUDE.md"
        alias.symlink_to(self.output)
        build(self.home)
        self.assertTrue(alias.is_symlink())
        self.assertEqual(alias.read_bytes(), self.output.read_bytes())
        self.assertEqual(stat.S_IMODE(self.output.stat().st_mode), 0o640)
        self.assertEqual(list(self.output.parent.glob(".AGENTS.md.*.tmp")), [])

    def test_invalid_sources_preserve_output(self):
        cases = [
            ("# only comments\n", "no instruction chapters"),
            ("missing.md\n", "missing.md"),
            ("one.md\none.md\n", "Duplicate"),
            ("/absolute.md\n", "Invalid chapter"),
            ("../outside.md\n", "escapes"),
            ("index.txt\n", "Invalid chapter"),
        ]
        (self.directory.parent / "outside.md").write_text("outside")
        for index, message in cases:
            with self.subTest(index=index):
                self.output.write_text("last good instructions")
                self.index.write_text(index)
                with self.assertRaisesRegex(InstructionError, message):
                    build(self.home)
                self.assertEqual(self.output.read_text(), "last good instructions")

    def test_symlinks_cannot_escape_and_aliases_cannot_repeat_chapters(self):
        outside = self.home / "outside.md"
        outside.write_text("outside")
        link = self.directory / "linked.md"
        link.symlink_to(outside)
        self.index.write_text("linked.md\n")
        with self.assertRaisesRegex(InstructionError, "escapes"):
            build(self.home)
        link.unlink()
        link.symlink_to(self.directory / "one.md")
        self.index.write_text("one.md\nlinked.md\n")
        with self.assertRaisesRegex(InstructionError, "Duplicate"):
            build(self.home)

    def test_output_symlink_is_refused_even_if_broken_or_checking(self):
        target = self.home / "target.md"
        for present in (False, True):
            with self.subTest(present=present):
                if present:
                    target.write_text("keep target")
                self.output.symlink_to(target)
                for check in (False, True):
                    with self.assertRaisesRegex(InstructionError, "symlink"):
                        build(self.home, check=check)
                self.assertTrue(self.output.is_symlink())
                if present:
                    self.assertEqual(target.read_text(), "keep target")
                self.output.unlink()

    def test_bad_encoding_and_unreadable_chapter_are_errors(self):
        chapter = self.directory / "one.md"
        chapter.write_bytes(b"\xff")
        with self.assertRaisesRegex(InstructionError, "UTF-8"):
            build(self.home)
        chapter.write_text("valid")

        def deny(path, *args, **kwargs):
            if Path(path).resolve() == chapter.resolve():
                raise PermissionError("chapter is unreadable")
            return original(path, *args, **kwargs)

        original = compiler.os.open
        with patch.object(compiler.os, "open", deny):
            with self.assertRaisesRegex(InstructionError, "unreadable"):
                build(self.home)

    def test_failed_replace_cleans_temporary_and_preserves_output(self):
        self.output.write_text("last good")
        with patch.object(compiler.os, "replace", side_effect=OSError("disk failure")):
            with self.assertRaisesRegex(InstructionError, "disk failure"):
                build(self.home)
        self.assertEqual(self.output.read_text(), "last good")
        self.assertEqual(list(self.output.parent.glob(".AGENTS.md.*.tmp")), [])

    def test_source_changed_during_build_retries_without_committing_mixed_content(self):
        original = compiler._unchanged
        checks = 0

        def edit(sources, root):
            nonlocal checks
            checks += 1
            if checks == 1:
                (self.directory / "one.md").write_text("new first")
                (self.directory / "parts/two.md").write_text("new second")
            return original(sources, root)

        with patch.object(compiler, "_unchanged", side_effect=edit):
            self.assertTrue(build(self.home))
        self.assertGreaterEqual(checks, 2)
        self.assertIn("new first", self.output.read_text())
        self.assertIn("new second", self.output.read_text())
        self.assertNotIn("# First", self.output.read_text())

    def test_continuous_edits_leave_last_good_output_and_no_temporary(self):
        self.output.write_text("last good")
        with patch.object(compiler, "_unchanged", return_value=False):
            with self.assertRaisesRegex(InstructionError, "kept changing"):
                build(self.home)
        self.assertEqual(self.output.read_text(), "last good")
        self.assertEqual(list(self.output.parent.glob(".AGENTS.md.*.tmp")), [])

    def test_same_size_edit_with_restored_mtime_is_detected(self):
        build(self.home)
        chapter = self.directory / "one.md"
        before = chapter.stat()
        chapter.write_text(chapter.read_text().replace("First", "Other"))
        os.utime(chapter, ns=(before.st_atime_ns, before.st_mtime_ns))
        self.assertTrue(build(self.home, check=True))
        self.assertTrue(build(self.home))
        self.assertIn("# Other", self.output.read_text())

    def test_check_on_missing_home_writes_nothing(self):
        missing_home = self.home / "absent"
        with self.assertRaises(InstructionError):
            build(missing_home, check=True)
        self.assertFalse(missing_home.exists())

    def test_source_fifo_is_rejected_before_open(self):
        fifo = self.directory / "pipe.md"
        os.mkfifo(fifo)
        self.index.write_text("pipe.md\n")
        with self.assertRaisesRegex(InstructionError, "not a regular file"):
            build(self.home)

    def test_index_symlink_in_subfolder_keeps_full_source_root(self):
        target = self.directory / "parts/order.txt"
        target.write_text("one.md\nparts/two.md\n")
        self.index.unlink()
        self.index.symlink_to(target)
        self.assertTrue(build(self.home))
        self.assertFalse(build(self.home))

    def test_source_root_escape_is_rejected(self):
        import shutil

        shutil.rmtree(self.directory)
        self.directory.symlink_to(self.home)
        with self.assertRaisesRegex(InstructionError, "escapes"):
            build(self.home)

    def test_build_holds_exclusive_lock_until_complete(self):
        original = compiler._snapshot
        lock_path = cache_dir_for(self.home) / "instructions.lock"

        def verify_lock(home):
            with lock_path.open("a+b") as other:
                with self.assertRaises(BlockingIOError):
                    fcntl.flock(other.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            return original(home)

        with patch.object(compiler, "_snapshot", side_effect=verify_lock):
            build(self.home)
        with lock_path.open("a+b") as other:
            fcntl.flock(other.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            fcntl.flock(other.fileno(), fcntl.LOCK_UN)

    def test_check_does_not_create_cache(self):
        self.assertTrue(build(self.home, check=True))
        self.assertFalse(cache_dir_for(self.home).exists())

    def test_output_alias_introduced_during_build_is_not_replaced(self):
        target = self.home / "target.md"
        target.write_text("keep target")
        original = compiler._unchanged

        def replace_output(sources, root):
            self.output.symlink_to(target)
            return original(sources, root)

        with patch.object(compiler, "_unchanged", side_effect=replace_output):
            with self.assertRaisesRegex(InstructionError, "symlink"):
                build(self.home)
        self.assertTrue(self.output.is_symlink())
        self.assertEqual(target.read_text(), "keep target")
        self.assertEqual(list(self.output.parent.glob(".AGENTS.md.*.tmp")), [])

    def test_missing_locking_support_rejects_build_and_check_before_io(self):
        missing_home = self.home / "unsupported-home"
        with patch.object(compiler, "fcntl", None):
            for check in (False, True):
                with self.subTest(check=check):
                    with self.assertRaisesRegex(InstructionError, "macOS/Linux"):
                        build(missing_home, check=check)
        self.assertFalse(missing_home.exists())

    def test_missing_no_follow_support_reports_instruction_error(self):
        with patch.object(compiler, "os", SimpleNamespace(O_NONBLOCK=1)):
            for check in (False, True):
                with self.subTest(check=check):
                    with self.assertRaisesRegex(InstructionError, "no-follow"):
                        build(self.home, check=check)

    def test_cli_help_and_version_work_when_fcntl_and_no_follow_are_unavailable(self):
        environment = dict(os.environ, HOME=str(self.home))
        environment["PYTHONPATH"] = str(Path(__file__).resolve().parents[1] / "src")
        script = """
import os
import sys
sys.modules["fcntl"] = None
if hasattr(os, "O_NOFOLLOW"):
    del os.O_NOFOLLOW
from swe.cli import main
sys.argv = ["swe", sys.argv[1]]
raise SystemExit(main())
"""
        for command, expected in (("--help", "instructions"), ("--version", "swe ")):
            with self.subTest(command=command):
                result = subprocess.run(
                    [sys.executable, "-c", script, command], env=environment,
                    capture_output=True, text=True, timeout=10)
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertIn(expected, result.stdout)
                self.assertEqual(result.stderr, "")

    def test_source_fingerprint_ignores_unlisted_files(self):
        before = compiler.source_fingerprint(self.home)
        (self.directory / "unused.md").write_text("not included")
        (self.directory / "extra").mkdir()
        (self.directory / "extra/unrelated.bin").write_bytes(b"unrelated")
        self.assertEqual(compiler.source_fingerprint(self.home), before)
        (self.directory / "one.md").write_text("changed")
        self.assertNotEqual(compiler.source_fingerprint(self.home), before)

    def test_source_fingerprint_has_stable_error_and_recovers(self):
        self.index.write_text("missing.md\n")
        invalid = compiler.source_fingerprint(self.home)
        self.assertEqual(compiler.source_fingerprint(self.home), invalid)
        (self.directory / "missing.md").write_text("recovered")
        self.assertNotEqual(compiler.source_fingerprint(self.home), invalid)

    def test_source_fingerprint_does_not_read_escaped_target(self):
        outside = self.home / "outside.md"
        outside.write_text("private")
        (self.directory / "linked.md").symlink_to(outside)
        self.index.write_text("linked.md\n")
        original = compiler.os.open

        def deny_external(path, *args, **kwargs):
            if Path(path).resolve() == outside.resolve():
                raise AssertionError("escaped target was opened")
            return original(path, *args, **kwargs)

        with patch.object(compiler.os, "open", side_effect=deny_external):
            invalid = compiler.source_fingerprint(self.home)
        self.assertEqual(compiler.source_fingerprint(self.home), invalid)


class HarnessTargetsTest(unittest.TestCase):
    """Per-harness compilation driven by AGENTS_MD/targets.json."""

    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.home = Path(self.temporary.name)
        self.directory = instructions_dir_for(self.home)
        self.directory.mkdir(parents=True)
        self.index = instructions_index_for(self.home)
        self.output = agents_file_for(self.home)
        self.targets = instructions_targets_for(self.home)
        self.index.write_text("one.md\nparts/two.md\n")
        (self.directory / "parts").mkdir()
        (self.directory / "one.md").write_text("# First\n")
        (self.directory / "parts/two.md").write_text("# Second\n")

    def write_targets(self, chapters: dict) -> None:
        import json

        self.targets.write_text(
            json.dumps({"version": 1, "chapters": chapters}))

    def test_no_targets_file_keeps_identical_output_bytes(self):
        self.assertTrue(build(self.home))
        content = self.output.read_text()
        self.assertTrue(content.startswith(compiler.GENERATED_MARKER + "\n\n"))
        self.assertIn("# First", content)
        self.assertIn("# Second", content)
        self.assertNotIn("Target:", content)
        self.assertEqual(
            list(self.home.glob(".swe/AGENTS.*.md")), [])

    def test_only_gives_the_named_harness_its_own_output(self):
        self.write_targets({"one.md": {"only": ["claude"]}})
        self.assertTrue(build(self.home))
        shared = self.output.read_text()
        self.assertNotIn("# First", shared)
        self.assertIn("# Second", shared)
        claude = harness_agents_file_for(self.home, "claude")
        lines = claude.read_text().splitlines()
        self.assertEqual(lines[0], compiler.GENERATED_MARKER)
        self.assertEqual(lines[1], "<!-- Target: claude -->")
        self.assertEqual(lines[2], "")
        content = claude.read_text()
        self.assertIn("# First", content)
        self.assertIn("# Second", content)
        self.assertLess(content.index("# First"), content.index("# Second"))

    def test_except_drops_the_chapter_from_the_named_harness(self):
        self.write_targets({"parts/two.md": {"except": ["codex"]}})
        build(self.home)
        self.assertIn("# Second", self.output.read_text())
        codex = harness_agents_file_for(self.home, "codex").read_text()
        self.assertIn("# First", codex)
        self.assertNotIn("# Second", codex)

    def test_named_harness_matching_the_default_gets_no_file(self):
        # codex is named, but only on a chapter that is not active.
        self.write_targets({"gone.md": {"except": ["codex"]},
                            "one.md": {"only": ["claude"]}})
        build(self.home)
        self.assertFalse(harness_agents_file_for(self.home, "codex").exists())
        self.assertTrue(harness_agents_file_for(self.home, "claude").exists())

    def test_invalid_targets_fail_and_preserve_outputs(self):
        self.output.write_text("last good")
        cases = [
            "{nope", "[]", '{"version": 2, "chapters": {}}',
            '{"version": 1, "chapters": []}',
            '{"version": 1, "chapters": {"one.md": {"only": "claude"}}}',
            '{"version": 1, "chapters": {"one.md": {"only": ["claude"], "except": []}}}',
            '{"version": 1, "chapters": {"one.md": {"only": ["Bad Name"]}}}',
            '{"version": 1, "chapters": {"one.md": {"only": ["claude"], "typo": 1}}}',
            '{"version": 1, "chapters": {"one.md": {}}}',
        ]
        for body in cases:
            with self.subTest(body=body):
                self.targets.write_text(body)
                with self.assertRaisesRegex(InstructionError, "targets.json"):
                    build(self.home)
                self.assertEqual(self.output.read_text(), "last good")
        self.targets.unlink()
        self.assertTrue(build(self.home))
        self.assertIn("# First", self.output.read_text())

    def test_check_reports_a_missing_per_harness_output_without_writing(self):
        self.write_targets({"one.md": {"only": ["claude"]}})
        build(self.home)
        self.assertFalse(build(self.home, check=True))
        harness_agents_file_for(self.home, "claude").unlink()
        result = build_run(self.home, check=True)
        self.assertTrue(result.changed)
        self.assertEqual(result.stale,
                         [str(harness_agents_file_for(self.home, "claude"))])
        self.assertFalse(harness_agents_file_for(self.home, "claude").exists())

    def test_rule_removal_repoints_links_and_deletes_the_stale_output(self):
        self.write_targets({"one.md": {"only": ["claude"]}})
        (self.home / ".claude").mkdir()
        link = self.home / ".claude" / "CLAUDE.md"
        link.symlink_to(self.output)
        build(self.home)
        claude = harness_agents_file_for(self.home, "claude")
        self.assertEqual(link.resolve(), claude.resolve())

        self.write_targets({})
        result = build_run(self.home)
        self.assertFalse(claude.exists())
        self.assertIn(str(claude), result.removed)
        self.assertEqual(link.resolve(), self.output.resolve())
        self.assertIn((str(link), str(self.output)), result.relinked)
        # A markerless lookalike is never removed.
        markerless = self.home / ".swe" / "AGENTS.foo.md"
        markerless.write_text("user file\n")
        build(self.home)
        self.assertEqual(markerless.read_text(), "user file\n")

    def test_relink_leaves_other_links_and_real_files_alone(self):
        self.write_targets({"one.md": {"only": ["claude"]}})
        (self.home / ".claude").mkdir()
        claude_link = self.home / ".claude" / "CLAUDE.md"
        claude_link.symlink_to(self.output)
        elsewhere = self.home / "elsewhere.md"
        elsewhere.write_text("other\n")
        alien = self.home / ".claude" / "alien.md"
        alien.symlink_to(elsewhere)
        real = self.home / ".claude" / "real.md"
        real.write_text("real\n")
        result = build_run(self.home)
        self.assertEqual((str(claude_link),
                          str(harness_agents_file_for(self.home, "claude"))),
                         result.relinked[0])
        self.assertEqual(os.readlink(alien), str(elsewhere))
        self.assertEqual(real.read_text(), "real\n")
        # A harness named in no rule keeps pointing at the shared output.
        (self.home / ".codex").mkdir()
        codex_link = self.home / ".codex" / "AGENTS.md"
        codex_link.symlink_to(self.output)
        build(self.home)
        self.assertEqual(codex_link.resolve(), self.output.resolve())

    def test_relink_skips_ignored_and_uninstalled_targets(self):
        self.write_targets({"one.md": {"only": ["claude"]}})
        ignored = self.home / ".claude" / "CLAUDE.md"
        (self.home / ".claude").mkdir()
        ignored.symlink_to(self.output)
        (self.home / ".swe" / ".linkignore").write_text(".claude\n")
        build(self.home)
        self.assertEqual(ignored.resolve(), self.output.resolve())
        # A link for a harness with no signature target is never created.
        self.assertFalse((self.home / ".codex").exists())

    def test_a_chain_into_an_output_is_left_for_its_owner(self):
        # Home Manager links CLAUDE.md to a nix-store entry that itself
        # links back to AGENTS.md: the first hop is not swe's, so the link
        # stays untouched and a note says where to aim the middle link.
        self.write_targets({"one.md": {"only": ["claude"]}})
        generation = self.home / "nix" / "generation"
        generation.parent.mkdir()
        (self.home / ".claude").mkdir()
        link = self.home / ".claude" / "CLAUDE.md"
        generation.symlink_to(self.output)
        link.symlink_to(generation)
        result = build_run(self.home)
        self.assertEqual(os.readlink(link), str(generation))
        self.assertEqual(result.relinked, [])
        self.assertTrue(any("through another link" in n for n in result.notes))
        self.assertTrue(any("AGENTS.claude.md" in n for n in result.notes))

    def test_a_symlinked_hub_root_still_relinks(self):
        # ~/.swe itself a link elsewhere: the hop key resolves the parent,
        # so a link into it is still recognised as swe's own.
        real_swe = self.home / "real-swe"
        real_swe.mkdir()
        (self.home / ".swe").rename(real_swe)
        (self.home / ".swe").symlink_to(real_swe)
        (self.home / ".claude").mkdir()
        link = self.home / ".claude" / "CLAUDE.md"
        link.symlink_to(agents_file_for(self.home))
        self.write_targets({"one.md": {"only": ["claude"]}})
        result = build_run(self.home)
        claude = harness_agents_file_for(self.home, "claude")
        self.assertEqual(os.readlink(link), str(claude))
        self.assertIn((str(link), str(claude)), result.relinked)

    def test_unreadable_linkignore_skips_relinking_with_a_note(self):
        self.write_targets({"one.md": {"only": ["claude"]}})
        (self.home / ".claude").mkdir()
        link = self.home / ".claude" / "CLAUDE.md"
        link.symlink_to(self.output)
        (self.home / ".swe" / ".linkignore").mkdir()  # a directory: unreadable
        result = build_run(self.home)
        self.assertTrue(result.notes)
        self.assertEqual(link.resolve(), self.output.resolve())

    def test_survey_reports_entries_outputs_and_chapter_rules(self):
        self.index.write_text("one.md\n# off.md\nparts/two.md\n# note.txt\n")
        (self.directory / "off.md").write_text("# Off\n")
        self.write_targets({"one.md": {"only": ["claude"]}})
        build(self.home)
        doc = compiler.survey(self.home)
        self.assertEqual(doc["targets"], str(self.targets))
        self.assertTrue(doc["targets_exists"])
        self.assertEqual(doc["entries"], [
            {"name": "one.md", "enabled": True},
            {"name": "off.md", "enabled": False},
            {"name": "parts/two.md", "enabled": True},
        ])
        by_name = {c["name"]: c for c in doc["chapters"]}
        self.assertEqual(by_name["one.md"]["only"], ["claude"])
        self.assertIsNone(by_name["one.md"]["except"])
        self.assertEqual(by_name["parts/two.md"]["only"], None)
        self.assertEqual(doc["outputs"][0]["harness"], None)
        self.assertEqual(doc["outputs"][0]["chapters"], ["parts/two.md"])
        self.assertEqual(doc["outputs"][1]["harness"], "claude")
        self.assertEqual(doc["outputs"][1]["chapters"],
                         ["one.md", "parts/two.md"])
        self.assertTrue(all(o["exists"] for o in doc["outputs"]))
        # A comment naming no real chapter stays a plain comment.
        self.index.write_text("one.md\n# notes.txt\n# not-real.md\n")
        self.assertEqual([e["name"] for e in compiler.survey(self.home)["entries"]],
                         ["one.md"])

    def test_survey_stale_covers_per_harness_outputs(self):
        self.write_targets({"one.md": {"only": ["claude"]}})
        doc = compiler.survey(self.home)
        self.assertTrue(doc["stale"])
        build(self.home)
        self.assertFalse(compiler.survey(self.home)["stale"])
        # A retired generated output is stale even when AGENTS.md is current.
        ghost = self.home / ".swe" / "AGENTS.ghost.md"
        ghost.write_text(compiler.GENERATED_MARKER + "\n")
        self.assertTrue(compiler.survey(self.home)["stale"])

    def test_invalid_targets_survey_carries_the_error(self):
        self.targets.write_text("{nope")
        doc = compiler.survey(self.home)
        self.assertIn("targets.json", doc["error"])

    def test_targets_file_changes_the_source_fingerprint(self):
        before = compiler.source_fingerprint(self.home)
        self.write_targets({"one.md": {"only": ["claude"]}})
        self.assertNotEqual(compiler.source_fingerprint(self.home), before)


