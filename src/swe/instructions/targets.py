"""Per-chapter harness rules from ``AGENTS_MD/targets.json``.

The file is optional. It maps a chapter path (as index.txt names it) to
exactly one of ``only`` or ``except``, each a list of harness registry
names. A chapter with no rule reaches every harness; ``only`` limits it to
the named ones; ``except`` keeps it from the named ones. ``only: []``
means no harness gets the chapter.

A harness whose resolved chapter set differs from the default gets its own
compiled output, ``~/.swe/AGENTS.<name>.md``; every other harness keeps
reading ``~/.swe/AGENTS.md``. This module imports only the standard
library and ``swe.paths`` so ``swe init``'s layout can consult it without
a cycle.
"""

from __future__ import annotations

import json
import os
from pathlib import Path, PurePosixPath
import re

from swe import paths as _paths

# Harness names are registry keys: qwen-code, mistral-vibe, devin, ...
_NAME = re.compile(r"^[a-z0-9][a-z0-9._-]*$")

# Enough of compiler.GENERATED_MARKER to recognise swe's own output without
# importing the compiler (which would be a cycle through this module).
_GENERATED_PREFIX = "<!-- Generated by swe instructions build"


def normalized(name: str) -> str:
    """An index or rule name in canonical form: ``./one.md`` -> ``one.md``."""
    return PurePosixPath(name).as_posix()


class TargetsError(ValueError):
    """targets.json exists but cannot be used; the message names the file."""


def targets_file(home: Path | None = None) -> Path:
    return _paths.instructions_targets_for(home)


def parse(text: str, path: Path) -> dict[str, dict[str, frozenset[str]]]:
    """chapter name -> {"only": names} or {"except": names}.

    Raises :class:`TargetsError` on invalid JSON, a version other than 1,
    a rule with both or neither key, and names outside the registry shape.
    """
    try:
        data = json.loads(text)
    except ValueError as exc:
        raise TargetsError(f"{path}: invalid JSON ({exc})") from exc
    if not isinstance(data, dict) or data.get("version") != 1:
        raise TargetsError(f'{path}: expected {{"version": 1, "chapters": {{...}}}}')
    chapters = data.get("chapters")
    if not isinstance(chapters, dict):
        raise TargetsError(f'{path}: "chapters" must be an object')
    rules: dict[str, dict[str, frozenset[str]]] = {}
    for chapter, rule in chapters.items():
        if not isinstance(chapter, str) or not isinstance(rule, dict) \
                or set(rule) - {"only", "except"}:
            raise TargetsError(
                f'{path}: rule for {chapter!r} must be an object holding '
                'exactly one of "only" or "except"')
        if len(rule) != 1:
            raise TargetsError(
                f'{path}: {chapter!r} takes exactly one of "only" or "except"')
        kind, names = next(iter(rule.items()))
        if not isinstance(names, list) or any(
                not isinstance(name, str) or not _NAME.match(name)
                for name in names):
            raise TargetsError(
                f'{path}: {chapter!r} "{kind}" must be a list of harness names')
        chapter = normalized(chapter)
        if chapter in rules:
            raise TargetsError(
                f"{path}: two rules name the same chapter: {chapter!r}")
        rules[chapter] = {kind: frozenset(names)}
    return rules


def load(home: Path | None = None) -> dict[str, dict[str, frozenset[str]]]:
    """The rules in targets.json; ``{}`` when absent, unreadable or invalid.

    The build reports an invalid file as an error through ``parse``; this
    forgiving read is for code that only resolves canonical paths, where an
    invalid file must not route a harness away from AGENTS.md.
    """
    path = targets_file(home)
    try:
        return parse(_read_regular(path), path)
    except (OSError, UnicodeError, TargetsError):
        return {}


def named_harnesses(rules: dict[str, dict[str, frozenset[str]]]) -> set[str]:
    """Every harness name any rule mentions."""
    out: set[str] = set()
    for rule in rules.values():
        out.update(next(iter(rule.values())))
    return out


def active_names(home: Path | None = None) -> list[str]:
    """The normalized active index lines, forgiving like the survey read."""
    try:
        lines = _read_regular(_paths.instructions_index_for(home)).splitlines()
    except (OSError, UnicodeError):
        return []
    return [normalized(line.strip()) for line in lines
            if line.strip() and not line.strip().startswith("#")]


def resolve(
    rules: dict[str, dict[str, frozenset[str]]], active: list[str]
) -> dict[str | None, list[str]]:
    """harness name (``None`` = every unnamed harness) -> its chapters.

    Rules for chapters index.txt does not activate are ignored, so an off
    chapter's names do not create outputs. ``None`` maps to the default
    set; each named harness whose set differs follows, sorted by name.
    """
    applicable = {c: r for c, r in rules.items() if c in active}
    active_set = set(applicable)

    def chapters_for(harness: str | None) -> list[str]:
        out = []
        for chapter in active:
            rule = applicable.get(chapter)
            if rule is None:
                out.append(chapter)
            elif "only" in rule:
                if harness is not None and harness in rule["only"]:
                    out.append(chapter)
            elif harness not in rule["except"]:
                out.append(chapter)
        return out

    resolved: dict[str | None, list[str]] = {None: chapters_for(None)}
    for harness in sorted(named_harnesses(
            {c: r for c, r in rules.items() if c in active_set})):
        chapters = chapters_for(harness)
        if chapters != resolved[None]:
            resolved[harness] = chapters
    return resolved


def generated(path: Path) -> bool:
    """True when ``path``'s first line carries the generated marker."""
    try:
        if not path.is_file():
            return False
        descriptor = os.open(path, os.O_RDONLY | os.O_NONBLOCK)
        with os.fdopen(descriptor, "r", encoding="utf-8", errors="replace") as handle:
            return _GENERATED_PREFIX in handle.readline()
    except OSError:
        return False


def _read_regular(path: Path) -> str:
    """``path``'s text, refusing anything but a regular file without blocking.

    A FIFO or device named like a source would otherwise hang a forgiving
    read (canonical paths, the watcher's output list).
    """
    if not path.is_file():
        raise OSError(f"not a regular file: {path}")
    descriptor = os.open(path, os.O_RDONLY | os.O_NONBLOCK)
    with os.fdopen(descriptor, "r", encoding="utf-8") as handle:
        return handle.read()


def harness_outputs(home: Path | None) -> dict[str, Path]:
    """name -> path of every generated ``AGENTS.<name>.md`` in the hub."""
    out: dict[str, Path] = {}
    try:
        candidates = _paths.swe_dir_for(home).glob("AGENTS.*.md")
    except OSError:
        return out
    for path in candidates:
        name = path.name[len("AGENTS."):-len(".md")]
        if name and generated(path):
            out[name] = path
    return out


def canonical_output(home: Path | None, harness: str) -> Path:
    """The file ``harness``'s links should point at.

    Its own compiled output when the file exists with the generated marker
    and the harness is still named in a valid targets.json; otherwise the
    shared AGENTS.md, so init never links to a not-yet-built or retired
    output.
    """
    path = _paths.harness_agents_file_for(home, harness)
    resolved = resolve(load(home), active_names(home))
    if harness in resolved and generated(path):
        return path
    return _paths.agents_file_for(home)


def valid_chapter_name(name: str) -> bool:
    """The index.txt chapter rules, without touching the filesystem."""
    if not name or Path(name).is_absolute() \
            or Path(name).suffix.lower() != ".md" \
            or any(character in name for character in ("\x00", "\r", "\n")) \
            or "-->" in name:
        return False
    return ".." not in Path(name).parts


def index_entries(home: Path | None = None) -> list[dict]:
    """``[{"name", "enabled"}]`` in index order: active plus off chapters.

    An off chapter is a ``# <path>.md`` comment naming a real chapter file
    that no active line lists: it holds the chapter's slot in the index
    while staying out of every build, which older swe versions honour too
    since they only ever read active lines.
    """
    directory = _paths.instructions_dir_for(home)
    try:
        lines = _read_regular(_paths.instructions_index_for(home)).splitlines()
    except (OSError, UnicodeError):
        return []
    active = {normalized(line.strip()) for line in lines
              if line.strip() and not line.strip().startswith("#")}
    try:
        root = directory.resolve()
    except OSError:
        root = directory
    entries: list[dict] = []
    for line in lines:
        stripped = line.strip()
        if not stripped:
            continue
        if not stripped.startswith("#"):
            entries.append({"name": normalized(stripped), "enabled": True})
            continue
        rest = normalized(stripped[1:].strip())
        if not valid_chapter_name(rest) or rest in active:
            continue
        candidate = directory / rest
        try:
            if not candidate.is_file() or not candidate.resolve().is_relative_to(root):
                continue
        except OSError:
            continue
        entries.append({"name": rest, "enabled": False})
    return entries
